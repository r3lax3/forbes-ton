function t(lang, key, params = {}) {
    const str = (translations[lang] && translations[lang][key]) || translations['ru'][key] || key;
    return str.replace(/\{(\w+)\}/g, (_, k) => params[k] !== undefined ? params[k] : `{${k}}`);
}

function getFrontendTranslations(lang) {
    const result = {};
    const src = translations[lang] || translations['ru'];
    for (const key of Object.keys(src)) {
        if (key.startsWith('f_')) {
            result[key] = src[key];
        }
    }
    return result;
}

module.exports = { t, getFrontendTranslations, translations };
